package com.hitorro.fleet.mailanalytics.ingest;

import com.hitorro.fleet.mailanalytics.entities.Watermark;
import com.sun.net.httpserver.HttpsConfigurator;
import com.sun.net.httpserver.HttpsServer;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import java.io.FileInputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.cert.X509Certificate;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicReference;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** BridgeMailSource against a stub bridge: an HTTPS server with a throwaway
 *  self-signed certificate generated by keytool at test time. All data is
 *  synthetic. */
class BridgeMailSourceTest {

    static final String TOKEN = "stub-token-0123456789abcdefghijklmnopqrstuvwxyz";
    static HttpsServer server;
    static String fingerprint;
    static Path dir;
    static final AtomicReference<String> lastQuery = new AtomicReference<>();
    static final AtomicReference<String> lastAuth = new AtomicReference<>();
    static volatile int statusOverride = 0;

    static final String PAGE = """
        {"messages":[
          {"id":41,"message_id":"msg-41@example.com","remote_id":"9001","date_received":"2026-11-18T10:00:00Z",
           "from":{"address":"Alice@Example.COM","name":"Alice"},"to":[{"address":"bob@example.org"}],
           "cc":[{"address":"carol@example.net"},{"address":"dan@example.net"}],"subject":"Quarterly numbers",
           "snippet":"synthetic preview","mailbox":"imap://acct/INBOX","flags":{"read":true,"flagged":false},"size":2048},
          {"id":42,"date_received":"2026-11-19T10:00:00Z","from":{"address":"noreply"},"to":[],"cc":[],
           "subject":"","flags":{"read":false,"flagged":true},"size":10}
        ],"next_since":42,"has_more":false}
        """;

    @BeforeAll
    static void start() throws Exception {
        dir = Files.createTempDirectory("bridge-test");
        Path ks = dir.resolve("stub.p12");
        String keytool = Path.of(System.getProperty("java.home"), "bin", "keytool").toString();
        Process p = new ProcessBuilder(keytool, "-genkeypair", "-alias", "stub", "-keyalg", "EC", "-groupname", "secp256r1",
                "-dname", "CN=not-the-hostname", "-validity", "2", "-storetype", "PKCS12",
                "-keystore", ks.toString(), "-storepass", "changeit", "-keypass", "changeit")
                .redirectErrorStream(true).start();
        p.getInputStream().readAllBytes();
        assertThat(p.waitFor()).isZero();

        KeyStore store = KeyStore.getInstance("PKCS12");
        try (var in = new FileInputStream(ks.toFile())) { store.load(in, "changeit".toCharArray()); }
        fingerprint = BridgeMailSource.sha256Hex((X509Certificate) store.getCertificate("stub"));
        KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        kmf.init(store, "changeit".toCharArray());
        SSLContext ctx = SSLContext.getInstance("TLS");
        ctx.init(kmf.getKeyManagers(), null, null);

        server = HttpsServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.setHttpsConfigurator(new HttpsConfigurator(ctx));
        server.createContext("/", ex -> {
            lastQuery.set(ex.getRequestURI().getRawQuery());
            String auth = ex.getRequestHeaders().getFirst("Authorization");
            lastAuth.set(auth);
            int code = 200;
            String body;
            if (!("Bearer " + TOKEN).equals(auth)) {
                code = 401;
                body = "{\"error\":\"unauthorized\"}";
            } else if (statusOverride != 0) {
                code = statusOverride;
                body = "{\"error\":\"no_access\"}";
            } else if (ex.getRequestURI().getPath().equals("/v1/status")) {
                body = "{\"mail\":{\"ok\":true,\"counts\":{\"messages\":2,\"max_id\":42}}}";
            } else {
                body = PAGE;
            }
            byte[] b = body.getBytes(StandardCharsets.UTF_8);
            ex.getResponseHeaders().set("Content-Type", "application/json");
            ex.sendResponseHeaders(code, b.length);
            ex.getResponseBody().write(b);
            ex.close();
        });
        server.start();
    }

    @AfterAll
    static void stop() { if (server != null) server.stop(0); }

    @BeforeEach
    void reset() { statusOverride = 0; }

    Map<String, String> config(String token, String fp) {
        Map<String, String> c = new HashMap<>();
        // Keys as Spring binds them from environment variables (no dashes).
        c.put("baseurl", "https://127.0.0.1:" + server.getAddress().getPort());
        c.put("token", token);
        c.put("fingerprint", fp);
        c.put("max-age-days", "7");
        return c;
    }

    static final Clock CLOCK = Clock.fixed(Instant.parse("2026-11-20T00:00:00Z"), ZoneOffset.UTC);

    @Test
    void fetches_and_maps_a_page_with_a_pinned_certificate() {
        // Colon-separated upper-case form, as the bridge prints it.
        String printed = fingerprint.toUpperCase().replaceAll("(..)(?!$)", "$1:");
        BridgeMailSource src = new BridgeMailSource("m1-mail", config(TOKEN, printed), CLOCK);
        Watermark wm = new Watermark();
        wm.setLastRowId(40L);

        List<RawMail> rows = src.fetchSince(wm, 5000).toList();

        assertThat(lastAuth.get()).isEqualTo("Bearer " + TOKEN);
        long after = Instant.parse("2026-11-13T00:00:00Z").getEpochSecond();
        assertThat(lastQuery.get()).isEqualTo("since=40&limit=1000&received_after=" + after);
        assertThat(rows).hasSize(2);
        RawMail a = rows.get(0);
        assertThat(a.sourceId()).isEqualTo("m1-mail");
        assertThat(a.sourceCursor()).isEqualTo(41L);
        assertThat(a.messageId()).isEqualTo("msg-41@example.com");
        assertThat(a.dateReceived()).isEqualTo(Instant.parse("2026-11-18T10:00:00Z"));
        assertThat(a.senderAddress()).isEqualTo("Alice@Example.COM");
        assertThat(a.senderDomain()).isEqualTo("example.com");
        assertThat(a.subject()).isEqualTo("Quarterly numbers");
        assertThat(a.bodyPreview()).isEqualTo("synthetic preview");
        assertThat(a.read()).isTrue();
        assertThat(a.recipientCount()).isEqualTo(3);
        assertThat(a.sizeBytes()).isEqualTo(2048);
        RawMail b = rows.get(1);
        assertThat(b.messageId()).isEqualTo("macmail:42");
        assertThat(b.senderDomain()).isEmpty();
        assertThat(b.flagged()).isTrue();
    }

    @Test
    void first_fetch_starts_at_zero() {
        BridgeMailSource src = new BridgeMailSource("m1", config(TOKEN, fingerprint), CLOCK);
        src.fetchSince(new Watermark(), 100).toList();
        assertThat(lastQuery.get()).startsWith("since=0&limit=100&received_after=");
    }

    @Test
    void refuses_a_certificate_that_does_not_match_the_pin() {
        String other = "ab".repeat(32);
        BridgeMailSource src = new BridgeMailSource("m1", config(TOKEN, other), CLOCK);
        lastAuth.set(null);
        assertThatThrownBy(() -> src.fetchSince(new Watermark(), 10).toList())
                .isInstanceOf(SqliteMailSource.IngestException.class)
                .hasMessageContaining("unreachable");
        assertThat(lastAuth.get()).as("no request (and no token) may reach an unpinned server").isNull();
        assertThat(src.health().ok()).isFalse();
    }

    @Test
    void reports_a_wrong_token_and_no_full_disk_access() {
        BridgeMailSource bad = new BridgeMailSource("m1", config("wrong-token-xxxxxxxxxxxxxxxxxxxxxxxx", fingerprint), CLOCK);
        assertThatThrownBy(() -> bad.fetchSince(new Watermark(), 10))
                .hasMessageContaining("401");
        statusOverride = 503;
        BridgeMailSource src = new BridgeMailSource("m1", config(TOKEN, fingerprint), CLOCK);
        assertThatThrownBy(() -> src.fetchSince(new Watermark(), 10))
                .hasMessageContaining("Full Disk Access");
    }

    @Test
    void health_reports_counts() {
        BridgeMailSource src = new BridgeMailSource("m1", config(TOKEN, fingerprint), CLOCK);
        MailSource.Health h = src.health();
        assertThat(h.ok()).isTrue();
        assertThat(h.detail()).contains("2 messages");
    }

    @Test
    void reads_token_and_fingerprint_from_files_and_validates_config() throws Exception {
        Path tok = Files.writeString(dir.resolve("token"), TOKEN + "\n");
        Path fp = Files.writeString(dir.resolve("fingerprint"), fingerprint + "\n");
        Map<String, String> c = new HashMap<>();
        c.put("base-url", "https://127.0.0.1:" + server.getAddress().getPort() + "/");
        c.put("token-file", tok.toString());
        c.put("fingerprint_file", fp.toString());
        assertThat(new BridgeMailSource("m1", c, CLOCK).health().ok()).isTrue();

        Map<String, String> plain = new HashMap<>(c);
        plain.put("base-url", "http://127.0.0.1:1");
        assertThatThrownBy(() -> new BridgeMailSource("m1", plain)).hasMessageContaining("https");
        Map<String, String> noTok = new HashMap<>(c);
        noTok.remove("token-file");
        assertThatThrownBy(() -> new BridgeMailSource("m1", noTok)).hasMessageContaining("token");
        Map<String, String> shortFp = new HashMap<>(c);
        shortFp.remove("fingerprint_file");
        shortFp.put("fingerprint", "abcd");
        assertThatThrownBy(() -> new BridgeMailSource("m1", shortFp)).hasMessageContaining("SHA-256");
    }
}
